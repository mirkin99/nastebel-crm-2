 BEGIN PERFORM public.crm_create_order_v2(c,sub,current_date,3500,'',jsonb_build_array(jsonb_build_object('_meta',jsonb_build_object('subscription_delivery_no',1))),'subscription'); EXCEPTION WHEN others THEN caught:=true; END;
