 c:=public.crm_create_client('__CRUD_TEST__','','Contact','test','В работе','subscription',jsonb_build_object('start_date',current_date,'months',1,'deliveries_per_month',3,'bouquet_price',3500,'discount_percent',0,'status','active'),10500,'test',0,false);
